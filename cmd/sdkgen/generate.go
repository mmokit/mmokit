func (g *Generator) genClient() string {
	var b strings.Builder
	gameName := titleCase(g.schema.Game)

	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")
	b.WriteString("import { create, toBinary, fromBinary } from \"@bufbuild/protobuf\";\n")

	// Collect unique proto imports (sorted paths + symbols for deterministic output).
	imports := g.collectProtoImports()
	paths := make([]string, 0, len(imports))
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		symbols := imports[path]
		sort.Strings(symbols)
		fmt.Fprintf(&b, "import { %s } from \"%s\";\n", strings.Join(symbols, ", "), path)
	}

	// Import type-only for server event + operation response messages.
	typeImports := g.collectTypeImports()
	typePaths := make([]string, 0, len(typeImports))
	for path := range typeImports {
		typePaths = append(typePaths, path)
	}
	sort.Strings(typePaths)
	for _, path := range typePaths {
		symbols := typeImports[path]
		sort.Strings(symbols)
		fmt.Fprintf(&b, "import type { %s } from \"%s\";\n", strings.Join(symbols, ", "), path)
	}

	b.WriteString("import { Transport } from \"./transport.js\";\n")
	fmt.Fprintf(&b, "import { %sDeltaDecoder } from \"./delta-decoder.js\";\n", gameName)
	b.WriteString("import type { DeltaWorldUpdate } from \"./entities.js\";\n")
	hasTypedEvents := len(g.schema.BroadcastTypes) > 0 || len(g.schema.ServerEventTypes) > 0
	if hasTypedEvents {
		// TypedDispatcher routes both HandleAll[T] broadcasts and
		// RegisterEvent[T] typed server events. Per-typed-server-event
		// classes are imported eagerly so the on<EventName>(handler)
		// wrappers below can pass them to typedEvents.on.
		var imports []string
		imports = append(imports, "TypedDispatcher")
		for _, name := range serverEventClassNames(g.schema.ServerEventTypes) {
			imports = append(imports, name)
		}
		fmt.Fprintf(&b, "import { %s } from \"./broadcasts.js\";\n", strings.Join(imports, ", "))
	}

	// Import envelope schemas from engine proto.
	if len(g.schema.Operations) > 0 {
		b.WriteString("import { ClientEventSchema, ServerEventSchema, type ServerEvent, OperationRequestSchema, OperationResponseSchema, type OperationResponse } from \"@gen/enginepb/engine_pb.js\";\n")
	} else {
		b.WriteString("import { ClientEventSchema, ServerEventSchema, type ServerEvent } from \"@gen/enginepb/engine_pb.js\";\n")
	}

	b.WriteString("\n")

	// Options interface.
	fmt.Fprintf(&b, "export interface %sClientOptions {\n", gameName)
	b.WriteString("  url: string;\n")
	b.WriteString("  onOpen?: () => void;\n")
	b.WriteString("  onClose?: (ev: CloseEvent) => void;\n")
	b.WriteString("  onError?: (ev: Event) => void;\n")
	b.WriteString("}\n\n")

	// Client class.
	fmt.Fprintf(&b, "export class %sClient {\n", gameName)
	b.WriteString("  private transport: Transport;\n")
	fmt.Fprintf(&b, "  private decoder = new %sDeltaDecoder();\n", gameName)
	b.WriteString("  private eventHandlers = new Map<number, ((data: Uint8Array) => void)[]>();\n")
	b.WriteString("  private rawEventHandlers: ((code: number, data: Uint8Array) => void)[] = [];\n")
	if hasTypedEvents {
		b.WriteString("  /** Typed broadcast dispatcher — register handlers for AoI-filtered\n")
		b.WriteString("   *  events emitted by the server's HandleAll[T] machinery. */\n")
		b.WriteString("  readonly typedEvents = new TypedDispatcher();\n")
	}
	if len(g.schema.Operations) > 0 {
		b.WriteString("  private pendingOps = new Map<number, { resolve: (data: Uint8Array) => void; reject: (err: Error) => void }>();\n")
		b.WriteString("  private pushHandlers = new Map<number, ((data: Uint8Array) => void)[]>();\n")
		b.WriteString("  private nextRequestID = 1;\n")
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "  constructor(private options: %sClientOptions) {\n", gameName)
	b.WriteString("    this.transport = new Transport(options.url);\n")
	b.WriteString("  }\n\n")

	// connect / disconnect / connected
	b.WriteString("  connect(): void {\n")
	b.WriteString("    this.transport.connect();\n")
	b.WriteString("    const ws = this.transport.socket!;\n")
	b.WriteString("    if (this.options.onOpen) ws.onopen = this.options.onOpen;\n")
	b.WriteString("    if (this.options.onClose) ws.onclose = this.options.onClose;\n")
	b.WriteString("    if (this.options.onError) ws.onerror = this.options.onError;\n")
	b.WriteString("    this.transport.onEvent((payload) => this.handleEvent(payload));\n")
	if len(g.schema.Operations) > 0 {
		b.WriteString("    this.transport.onOperation((payload) => this.handleOperation(payload));\n")
	}
	b.WriteString("  }\n\n")

	if len(g.schema.Operations) > 0 {
		b.WriteString("  disconnect(): void {\n")
		b.WriteString("    // Reject any pending operations.\n")
		b.WriteString("    for (const pending of this.pendingOps.values()) {\n")
		b.WriteString("      pending.reject(new Error(\"client disconnected\"));\n")
		b.WriteString("    }\n")
		b.WriteString("    this.pendingOps.clear();\n")
		b.WriteString("    this.transport.close();\n")
		b.WriteString("  }\n")
	} else {
		b.WriteString("  disconnect(): void { this.transport.close(); }\n")
	}
	b.WriteString("  get connected(): boolean { return this.transport.connected; }\n\n")

	b.WriteString("  /** Raw transport handle for advanced use (operations channel,\n")
	b.WriteString("   *  custom protocol extensions). Most app code should use the typed\n")
	b.WriteString("   *  send* / on* methods on this class instead. */\n")
	b.WriteString("  get rawTransport(): Transport { return this.transport; }\n\n")

	// Event dispatch.
	//
	// Channel 0x00 carries two coexisting wire formats during the
	// events-channel-redesign migration:
	//
	//   1. Legacy ServerEvent envelope: protobuf wire format. The first
	//      byte is the field-1 varint tag for the `code` field (0x08).
	//      Decoded as before via ServerEventSchema.
	//
	//   2. New typed-event frame: repeated [typeID:u32 LE][body_len:u32 LE][body]
	//      until end of message. Each entry dispatches to typedEvents.
	//
	// Disambiguation: the first byte of the payload. ServerEvent always
	// starts with 0x08 (the field-1 varint tag for `code`); a typed-event
	// frame's first byte is the low byte of an FNV-1a typeID hash, which
	// has a 1/256 chance of being 0x08. Collisions panic at registration
	// time on the server (mmokit.RegisterEvent[T]) — if the legacy decode
	// throws here, we log a defensive warning hinting at the collision.
	//
	// Phase 2.4 retires WorldUpdateMsg.events; Phase 7 retires the legacy
	// ServerEvent envelope entirely. Until then, both paths coexist.
	b.WriteString("  private handleEvent(payload: Uint8Array): void {\n")
	b.WriteString("    if (payload.length === 0) return;\n")
	if hasTypedEvents {
		b.WriteString("    if (payload[0] !== 0x08) {\n")
		b.WriteString("      // Typed-event frame: repeated [typeID:u32 LE][body_len:u32 LE][body].\n")
		b.WriteString("      let off = 0;\n")
		b.WriteString("      while (off + 8 <= payload.length) {\n")
		b.WriteString("        const view = new DataView(payload.buffer, payload.byteOffset + off, 8);\n")
		b.WriteString("        const typeID = view.getUint32(0, true);\n")
		b.WriteString("        const bodyLen = view.getUint32(4, true);\n")
		b.WriteString("        off += 8;\n")
		b.WriteString("        if (off + bodyLen > payload.length) {\n")
		b.WriteString("          console.warn(`typed-event frame: truncated body for typeID=0x${typeID.toString(16)}`);\n")
		b.WriteString("          return;\n")
		b.WriteString("        }\n")
		b.WriteString("        const body = payload.subarray(off, off + bodyLen);\n")
		b.WriteString("        off += bodyLen;\n")
		b.WriteString("        this.typedEvents.dispatch(typeID, body);\n")
		b.WriteString("      }\n")
		b.WriteString("      return;\n")
		b.WriteString("    }\n")
	}
	b.WriteString("    let evt: ServerEvent;\n")
	b.WriteString("    try {\n")
	b.WriteString("      evt = fromBinary(ServerEventSchema, payload) as ServerEvent;\n")
	b.WriteString("    } catch (err) {\n")
	b.WriteString("      console.warn(`legacy ServerEvent decode failed (first byte 0x${payload[0].toString(16)}); this might be a typed-event frame whose typeID's low byte is 0x08 — rename the offending Go type. err=${err}`);\n")
	b.WriteString("      return;\n")
	b.WriteString("    }\n")
	b.WriteString("    const handlers = this.eventHandlers.get(evt.code);\n")
	b.WriteString("    if (handlers) {\n")
	b.WriteString("      for (const h of handlers) h(evt.data);\n")
	b.WriteString("    }\n")
	b.WriteString("    for (const h of this.rawEventHandlers) h(evt.code, evt.data);\n")
	b.WriteString("  }\n\n")

	b.WriteString("  private on(code: number, handler: (data: Uint8Array) => void): () => void {\n")
	b.WriteString("    let arr = this.eventHandlers.get(code);\n")
	b.WriteString("    if (!arr) { arr = []; this.eventHandlers.set(code, arr); }\n")
	b.WriteString("    arr.push(handler);\n")
	b.WriteString("    return () => { const idx = arr!.indexOf(handler); if (idx >= 0) arr!.splice(idx, 1); };\n")
	b.WriteString("  }\n\n")

	// Send helper.
	b.WriteString("  private sendEvent(code: number, data: Uint8Array): void {\n")
	b.WriteString("    const evt = create(ClientEventSchema, { code, data });\n")
	b.WriteString("    this.transport.sendEvent(toBinary(ClientEventSchema, evt));\n")
	b.WriteString("  }\n\n")

	// --- Typed client-input send ---
	//
	// Wire path: TS class instance → encode() body bytes → transport
	// sendClientInput frames as [0x02][u32 typeID][u32 bodyLen][body].
	// Server-side ReflectUnmarshalOnStage decodes the body back into
	// the registered Go type and dispatches via mmokit.HandleClient.
	//
	// The TS-side type bound matches every class generated in inputs.ts:
	// each has `static readonly typeID: number` and an `encode(): Uint8Array`
	// instance method. This signature works whether or not inputs.ts was
	// emitted (the server's HandleClient registry may be empty).
	b.WriteString("  /** Send a typed client-input message (mmokit.HandleClient).\n")
	b.WriteString("   *\n")
	b.WriteString("   *  msg must be an instance of a class generated into inputs.ts —\n")
	b.WriteString("   *  exposing static typeID and instance encode(): Uint8Array. The\n")
	b.WriteString("   *  resulting wire frame is dispatched server-side to the matching\n")
	b.WriteString("   *  HandleClient[T] handler. */\n")
	b.WriteString("  send(msg: { encode(): Uint8Array }): void {\n")
	b.WriteString("    const ctor = msg.constructor as unknown as { typeID: number };\n")
	b.WriteString("    this.transport.sendClientInput(ctor.typeID, msg.encode());\n")
	b.WriteString("  }\n\n")

	// --- Client → Server send methods ---
	for _, ce := range g.schema.ClientEvents {
		msg := g.resolveMsg(ce.ProtoName)
		if msg == nil {
			continue
		}
		methodName := "send" + titleCase(protoToMethodName(msg.TypeName, g.schema.Game))
		fmt.Fprintf(&b, "  /** Send %s (code %d). */\n", msg.TypeName, ce.Code)
		fmt.Fprintf(&b, "  %s(params: { %s }): void {\n", methodName, fieldParamList(msg.Fields))
		fmt.Fprintf(&b, "    const data = toBinary(%s, create(%s, params));\n", msg.SchemaName, msg.SchemaName)
		fmt.Fprintf(&b, "    this.sendEvent(%d, data);\n", ce.Code)
		b.WriteString("  }\n\n")
	}

	// Pre-compute the set of typed-event method names. During Phase 3 of the
	// events-channel-redesign migration, a single logical event (e.g.
	// PlayerDied) may be registered both via the legacy proto-envelope path
	// (gamepb.PlayerDiedMsg → onPlayerDied) AND via the typed path
	// (game.PlayerDied → onPlayerDied). Without dedupe we'd emit two TS
	// methods with the same name → TS error. Skip the legacy emit when a
	// typed equivalent exists; the typed path is the new canonical surface.
	typedMethodNames := map[string]struct{}{}
	for _, st := range g.schema.ServerEventTypes {
		typedMethodNames[serverEventMethodName(broadcastClassName(st.Name))] = struct{}{}
	}

	// --- Server → Client receive methods ---
	for _, se := range g.schema.ServerEvents {
		if se.ProtoName == "" {
			// Binary event (e.g. deltaWorldUpdate).
			methodName := "on" + titleCase(se.Name)
			fmt.Fprintf(&b, "  /** Subscribe to %s (code %d, binary). */\n", se.Name, se.Code)
			fmt.Fprintf(&b, "  %s(handler: (update: DeltaWorldUpdate) => void): () => void {\n", methodName)
			fmt.Fprintf(&b, "    return this.on(%d, (data) => handler(this.decoder.decode(data)));\n", se.Code)
			b.WriteString("  }\n\n")
		} else {
			msg := g.resolveMsg(se.ProtoName)
			if msg == nil {
				continue
			}
			methodName := "on" + titleCase(se.Name)
			if _, dup := typedMethodNames[methodName]; dup {
				// A typed RegisterEvent[T] for the same logical event already
				// emits this method — the typed path is the canonical surface.
				// Skip the legacy proto-envelope emit to avoid a TS duplicate
				// method declaration.
				continue
			}
			fmt.Fprintf(&b, "  /** Subscribe to %s (code %d). */\n", se.Name, se.Code)
			fmt.Fprintf(&b, "  %s(handler: (msg: %s) => void): () => void {\n", methodName, msg.TypeName)
			fmt.Fprintf(&b, "    return this.on(%d, (data) => handler(fromBinary(%s, data)));\n", se.Code, msg.SchemaName)
			b.WriteString("  }\n\n")
		}
	}

	// --- Typed server-event handlers (mmokit.RegisterEvent[T]) ---
	//
	// Each typed registration produces a `client.on<EventName>(handler)`
	// method that subscribes against the TypedDispatcher under the hood.
	// The dispatcher dispatches by typeID — set on the wire by the server's
	// afterSend path and matched against the class's static typeID.
	//
	// Naming convention: Go `pkg.PlayerSpawned` → TS class `PlayerSpawned`
	// (last dot segment) → method `onPlayerSpawned`.
	for _, st := range g.schema.ServerEventTypes {
		writeServerEventHandler(&b, st)
	}

	// --- Operations (request/response on channel 0x01) ---
	if len(g.schema.Operations) > 0 {
		// handleOperation dispatches responses to pending op requests (by requestId)
		// or to push handlers (when requestId == 0 — unsolicited server push).
		b.WriteString("  private handleOperation(payload: Uint8Array): void {\n")
		b.WriteString("    const resp = fromBinary(OperationResponseSchema, payload) as OperationResponse;\n")
		b.WriteString("    if (resp.requestId !== 0) {\n")
		b.WriteString("      const pending = this.pendingOps.get(resp.requestId);\n")
		b.WriteString("      if (pending) {\n")
		b.WriteString("        this.pendingOps.delete(resp.requestId);\n")
		b.WriteString("        if (resp.returnCode !== 0) {\n")
		b.WriteString("          pending.reject(new Error(resp.errorMsg || `op error code ${resp.returnCode}`));\n")
		b.WriteString("        } else {\n")
		b.WriteString("          pending.resolve(resp.data);\n")
		b.WriteString("        }\n")
		b.WriteString("      }\n")
		b.WriteString("      return;\n")
		b.WriteString("    }\n")
		b.WriteString("    const handlers = this.pushHandlers.get(resp.code);\n")
		b.WriteString("    if (handlers) for (const h of handlers) h(resp.data);\n")
		b.WriteString("  }\n\n")

		b.WriteString("  private onPush(code: number, handler: (data: Uint8Array) => void): () => void {\n")
		b.WriteString("    let arr = this.pushHandlers.get(code);\n")
		b.WriteString("    if (!arr) { arr = []; this.pushHandlers.set(code, arr); }\n")
		b.WriteString("    arr.push(handler);\n")
		b.WriteString("    return () => { const idx = arr!.indexOf(handler); if (idx >= 0) arr!.splice(idx, 1); };\n")
		b.WriteString("  }\n\n")

		// Generic op-channel send for opcodes whose proto types aren't in the
		// schema (e.g. service-kind ops like auth, which sdkgen doesn't yet
		// pick up). Callers marshal request/response themselves and hand raw
		// bytes through. Mirrors the typed-send machinery — assigns a fresh
		// requestId, registers a pendingOps slot, and resolves with the raw
		// response bytes (or rejects on returnCode != 0).
		b.WriteString("  /** Send a raw op (code, data) and await raw response bytes. For ops not in the typed schema. */\n")
		b.WriteString("  sendOp(code: number, data: Uint8Array): Promise<Uint8Array> {\n")
		b.WriteString("    const requestId = this.nextRequestID++;\n")
		b.WriteString("    const req = create(OperationRequestSchema, { code, requestId, data });\n")
		b.WriteString("    this.transport.sendOperation(toBinary(OperationRequestSchema, req));\n")
		b.WriteString("    return new Promise((resolve, reject) => {\n")
		b.WriteString("      this.pendingOps.set(requestId, { resolve, reject });\n")
		b.WriteString("    });\n")
		b.WriteString("  }\n\n")

		// Typed send method per operation.
		for _, op := range g.schema.Operations {
			reqMsg := g.resolveMsg(op.RequestProto)
			respMsg := g.resolveMsg(op.ResponseProto)
			if reqMsg == nil || respMsg == nil {
				continue
			}
			methodName := "send" + titleCase(op.Name)
			fmt.Fprintf(&b, "  /** Send %s request (op code %d), await typed %s. */\n", op.Name, op.Code, respMsg.TypeName)
			fmt.Fprintf(&b, "  %s(params: { %s }): Promise<%s> {\n", methodName, fieldParamList(reqMsg.Fields), respMsg.TypeName)
			fmt.Fprintf(&b, "    const data = toBinary(%s, create(%s, params));\n", reqMsg.SchemaName, reqMsg.SchemaName)
			b.WriteString("    const requestId = this.nextRequestID++;\n")
			fmt.Fprintf(&b, "    const req = create(OperationRequestSchema, { code: %d, requestId, data });\n", op.Code)
			b.WriteString("    this.transport.sendOperation(toBinary(OperationRequestSchema, req));\n")
			b.WriteString("    return new Promise((resolve, reject) => {\n")
			b.WriteString("      this.pendingOps.set(requestId, {\n")
			fmt.Fprintf(&b, "        resolve: (d) => resolve(fromBinary(%s, d) as %s),\n", respMsg.SchemaName, respMsg.TypeName)
			b.WriteString("        reject,\n")
			b.WriteString("      });\n")
			b.WriteString("    });\n")
			b.WriteString("  }\n\n")

			// Push subscriber: fires when server sends an unsolicited response for this op code.
			pushMethodName := "on" + titleCase(op.Name) + "Push"
			fmt.Fprintf(&b, "  /** Subscribe to unsolicited %s pushes (op code %d, requestId=0). */\n", op.Name, op.Code)
			fmt.Fprintf(&b, "  %s(handler: (msg: %s) => void): () => void {\n", pushMethodName, respMsg.TypeName)
			fmt.Fprintf(&b, "    return this.onPush(%d, (data) => handler(fromBinary(%s, data) as %s));\n", op.Code, respMsg.SchemaName, respMsg.TypeName)
			b.WriteString("  }\n\n")
		}
	}

	// Raw event handler.
	b.WriteString("  /** Catch-all for unhandled server events. */\n")
	b.WriteString("  onRawEvent(handler: (code: number, data: Uint8Array) => void): () => void {\n")
	b.WriteString("    this.rawEventHandlers.push(handler);\n")
	b.WriteString("    return () => {\n")
	b.WriteString("      const idx = this.rawEventHandlers.indexOf(handler);\n")
	b.WriteString("      if (idx >= 0) this.rawEventHandlers.splice(idx, 1);\n")
	b.WriteString("    };\n")
	b.WriteString("  }\n\n")

	// Baseline clear.
	b.WriteString("  /** Clear delta baselines (call on cell change / reconnect). */\n")
	b.WriteString("  clearBaselines(): void { this.decoder.clear(); }\n")

	b.WriteString("}\n")

	return b.String()
}

// typedShadowedServerEvents returns the set of legacy proto-based server-event
// codes whose method emit is suppressed because a typed RegisterEvent[T]
// equivalent owns the canonical method name. Used by import collectors so we
// don't emit dead `import { FooMsg, FooMsgSchema } from "@gen/..."` lines.
func (g *Generator) typedShadowedServerEvents() map[uint32]struct{} {
	typedNames := map[string]struct{}{}
	for _, st := range g.schema.ServerEventTypes {
		typedNames[serverEventMethodName(broadcastClassName(st.Name))] = struct{}{}
	}
	out := map[uint32]struct{}{}
	for _, se := range g.schema.ServerEvents {
		if se.ProtoName == "" {
			continue
		}
		if _, dup := typedNames["on"+titleCase(se.Name)]; dup {
			out[se.Code] = struct{}{}
		}
	}
	return out
}

// collectProtoImports collects Schema imports (for encoding/decoding) grouped by import path.
func (g *Generator) collectProtoImports() map[string][]string {
	imports := make(map[string][]string)
	seen := make(map[string]bool)
	addSchema := func(fullName string) {
		msg := g.resolveMsg(fullName)
		if msg == nil || seen[msg.SchemaName] {
			return
		}
		seen[msg.SchemaName] = true
		path := protoImportPath(msg)
		imports[path] = append(imports[path], msg.SchemaName)
	}
	for _, ce := range g.schema.ClientEvents {
		addSchema(ce.ProtoName)
	}
	shadowed := g.typedShadowedServerEvents()
	for _, se := range g.schema.ServerEvents {
		if se.ProtoName == "" {
			continue
		}
		if _, dup := shadowed[se.Code]; dup {
			continue
		}
		addSchema(se.ProtoName)
	}
	for _, op := range g.schema.Operations {
		addSchema(op.RequestProto)
		addSchema(op.ResponseProto)
	}
	return imports
}

// collectTypeImports collects type-only imports for server event + operation response types.
func (g *Generator) collectTypeImports() map[string][]string {
	imports := make(map[string][]string)
	seen := make(map[string]bool)
	addType := func(fullName string) {
		msg := g.resolveMsg(fullName)
		if msg == nil || seen[msg.TypeName] {
			return
		}
		seen[msg.TypeName] = true
		path := protoImportPath(msg)
		imports[path] = append(imports[path], msg.TypeName)
	}
	shadowed := g.typedShadowedServerEvents()
	for _, se := range g.schema.ServerEvents {
		if se.ProtoName == "" {
			continue
		}
		if _, dup := shadowed[se.Code]; dup {
			continue
		}
		addType(se.ProtoName)
	}
	for _, op := range g.schema.Operations {
		addType(op.ResponseProto)
	}
	return imports
}

// protoToMethodName strips game-prefix from proto message names for cleaner methods.
// "BasicMoveTargetMsg" with game="basic" → "MoveTarget"
func protoToMethodName(typeName string, game string) string {
	name := typeName
	prefix := titleCase(game)
	name = strings.TrimPrefix(name, prefix)
	name = strings.TrimSuffix(name, "Msg")
	if name == "" {
		return typeName
	}
	return name
}

func fieldParamList(fields []ProtoField) string {
	parts := make([]string, len(fields))
	for i, f := range fields {
		parts[i] = fmt.Sprintf("%s: %s", f.Name, f.Type)
	}
	return strings.Join(parts, "; ")
}

