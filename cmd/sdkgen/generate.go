func (g *Generator) genIndex() string {
	gameName := titleCase(g.schema.Game)
	var b strings.Builder
	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")
	fmt.Fprintf(&b, "export { %sClient } from \"./client.js\";\n", gameName)
	fmt.Fprintf(&b, "export type { %sClientOptions } from \"./client.js\";\n", gameName)
	b.WriteString("export type { AnyEntity, DeltaWorldUpdate } from \"./entities.js\";\n")
	b.WriteString("export * from \"./entities.js\";\n")
	fmt.Fprintf(&b, "export { %sDeltaDecoder } from \"./delta-decoder.js\";\n", gameName)
	b.WriteString("export { Transport } from \"./transport.js\";\n")
	if len(g.schema.BroadcastTypes) > 0 || len(g.schema.ServerEventTypes) > 0 {
		// Re-export every generated broadcast / typed-server-event class
		// plus the dispatcher so app code imports them via the SDK's public
		// surface, not directly from the internal broadcasts.ts file.
		var names []string
		names = append(names, "TypedDispatcher")
		for _, bt := range g.schema.BroadcastTypes {
			names = append(names, broadcastClassName(bt.Name))
		}
		for _, st := range g.schema.ServerEventTypes {
			names = append(names, broadcastClassName(st.Name))
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "export { %s } from \"./broadcasts.js\";\n", strings.Join(names, ", "))
	}
	if len(g.schema.ClientInputTypes) > 0 {
		// Re-export every generated client-input class so app code imports
		// them via the SDK's public surface (e.g. `import { SetMoveTarget }
		// from "@sdk"`) rather than reaching into the internal inputs.ts
		// file directly.
		var names []string
		for _, ct := range g.schema.ClientInputTypes {
			names = append(names, broadcastClassName(ct.Name))
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "export { %s } from \"./inputs.js\";\n", strings.Join(names, ", "))
	}

	// Re-export proto types that appear in the SDK's public method
	// signatures — consumers should not have to reach into @gen/... for
	// types the SDK already uses on its own surface.
	typeImports := g.collectTypeImports()
	paths := make([]string, 0, len(typeImports))
	for p := range typeImports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, path := range paths {
		names := append([]string(nil), typeImports[path]...)
		sort.Strings(names)
		fmt.Fprintf(&b, "export type { %s } from %q;\n", strings.Join(names, ", "), path)
	}

	return b.String()
}
