func (g *Generator) genEntities() string {
	var b strings.Builder
	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")

	var entityNames []string

	for _, ent := range g.schema.Entities {
		name := g.entityName(ent)
		entityNames = append(entityNames, name)

		fmt.Fprintf(&b, "/** Entity kind %d. */\n", ent.Kind)
		fmt.Fprintf(&b, "export interface %s {\n", name)
		b.WriteString("  netID: number;\n")
		b.WriteString("  /** Authority generation for this netID (uint32 serial). */\n")
		b.WriteString("  authorityEpoch: number;\n")
		fmt.Fprintf(&b, "  entityType: %d;\n", ent.Kind)
		b.WriteString("  /**\n")
		b.WriteString("   * Cluster-clock stamp (Unix ms) from the authoritative producer at\n")
		b.WriteString("   * the moment this state was emitted. Preserves the producer's\n")
		b.WriteString("   * timeline through any relay hops. Used as the per-entity time-base\n")
		b.WriteString("   * for snapshot interpolation.\n")
		b.WriteString("   */\n")
		b.WriteString("  producedAtMs: number;\n")

		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				if field.Initial {
					continue
				}
				tsType := encodingToTSType(field.Encoding)
				fmt.Fprintf(&b, "  %s: %s;\n", field.Name, tsType)
			}
		}
		// Initial fields.
		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				if !field.Initial {
					continue
				}
				tsType := encodingToTSType(field.Encoding)
				fmt.Fprintf(&b, "  %s: %s;\n", field.Name, tsType)
			}
		}

		// Var-tail field (if any).
		if ent.VarTail != nil {
			itemType := g.tailItemTypeName(ent)
			fmt.Fprintf(&b, "  %s: %s[];\n", ent.VarTail.Name, itemType)
		}

		b.WriteString("}\n\n")

		// Emit the var-tail item type interface after the entity interface.
		if ent.VarTail != nil {
			itemType := g.tailItemTypeName(ent)
			fmt.Fprintf(&b, "/** Item record for %s.%s var-tail. */\n", name, ent.VarTail.Name)
			fmt.Fprintf(&b, "export interface %s {\n", itemType)
			for _, f := range ent.VarTail.ItemFields {
				tsType := encodingToTSType(f.Encoding)
				fmt.Fprintf(&b, "  %s: %s;\n", f.Name, tsType)
			}
			b.WriteString("}\n\n")
		}
	}

	// Union type.
	if len(entityNames) > 0 {
		b.WriteString("export type AnyEntity = ")
		b.WriteString(strings.Join(entityNames, " | "))
		b.WriteString(";\n\n")
	}

	b.WriteString("export interface DeltaWorldUpdate {\n")
	b.WriteString("  tick: number;\n")
	b.WriteString("  seq: number;\n")
	b.WriteString("  /**\n")
	b.WriteString("   * Set when the server's ReplicationSystem sent this frame as the\n")
	b.WriteString("   * first frame to this connection — i.e. on initial login or on every\n")
	b.WriteString("   * cross-cell handoff. The SDK decoder clears its per-entity baselines\n")
	b.WriteString("   * before applying the frame; clients should treat the frame's Entered\n")
	b.WriteString("   * list as the authoritative current entity set and drop any stale\n")
	b.WriteString("   * entities they retained from before. Topology-transparent: clients\n")
	b.WriteString("   * never learn about cells, authority transfers, or server boundaries.\n")
	b.WriteString("   */\n")
	b.WriteString("  freshSnapshot: boolean;\n")
	b.WriteString("  /** True when the decoder adopted a new explicit stream generation. */\n")
	b.WriteString("  streamChanged: boolean;\n")
	b.WriteString("  /** Input sequence causally reflected by this frame; null on legacy/unsequenced streams. */\n")
	b.WriteString("  processedInputSeq: number | null;\n")
	b.WriteString("  entered: AnyEntity[];\n")
	b.WriteString("  updated: AnyEntity[];\n")
	b.WriteString("  removed: number[];\n")
	b.WriteString("  exited: number[];\n")
	b.WriteString("}\n")

	return b.String()
}

func (g *Generator) entityName(ent EntitySchema) string {
	if ent.Name != "" {
		return ent.Name + "Entity"
	}
	return fmt.Sprintf("Entity%d", ent.Kind)
}

// tailItemTypeName returns the generated TypeScript interface name for a
// var-tail's per-item record. Example: Ship → ShipStatusEffectsItem.
//
// Strips the trailing "Entity" suffix from entityName() so tail-item names
// read as ShipStatusEffectsItem rather than ShipEntityStatusEffectsItem.
func (g *Generator) tailItemTypeName(ent EntitySchema) string {
	if ent.VarTail == nil {
		return ""
	}
	name := strings.TrimSuffix(g.entityName(ent), "Entity")
	return name + titleCase(ent.VarTail.Name) + "Item"
}

func encodingToTSType(enc string) string {
	switch enc {
	case "string":
		return "string"
	case "bool":
		return "boolean"
	default:
		return "number"
	}
}

// ---------------------------------------------------------------------------
// delta-decoder.ts
// ---------------------------------------------------------------------------

func (g *Generator) genDeltaDecoder() string {
	var b strings.Builder
	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")
	b.WriteString("import {\n")
	b.WriteString("  readFloat32, readInt16, readUint16, readUint32,\n")
	b.WriteString("  unAngle, unNorm, unVel,\n")
	b.WriteString("  decodeFrameHeader, decodeFullEntry, decodeDeltaEntry, decodeRemovedIDs, decodeInputAck,\n")
	b.WriteString("  FRAME_FLAG_FRESH_SNAPSHOT,\n")
	b.WriteString("  applyDelta, BaselineStore,\n")
	b.WriteString("  decodeLengthPrefixedStringU8,\n")
	b.WriteString("} from \"./_core/delta-decoder-core.js\";\n")

	// Import entity types AND per-entity var-tail item types. The decode
	// functions below allocate slices typed as `<Entity><Tail>Item[]`, so
	// every entity with a var-tail contributes its item interface to the
	// import list alongside its entity interface.
	var entityNames []string
	for _, ent := range g.schema.Entities {
		entityNames = append(entityNames, g.entityName(ent))
		if item := g.tailItemTypeName(ent); item != "" {
			entityNames = append(entityNames, item)
		}
	}
	fmt.Fprintf(&b, "import type { %s, AnyEntity, DeltaWorldUpdate } from \"./entities.js\";\n\n", strings.Join(entityNames, ", "))

	// Generate per-entity constants and decode functions.
	for _, ent := range g.schema.Entities {
		name := g.entityName(ent)
		upperName := strings.ToUpper(name)

		// Field sizes array — strip the trailing -1 var-tail marker. The
		// client-side applyDelta expects only the fixed field sizes and takes
		// hasVarTail as a separate boolean. Leaving the -1 in the array
		// miscounts totalLogicalFields and fixedSize, corrupting delta
		// application.
		fixedLayout := ent.Layout
		hasVarTail := false
		if len(fixedLayout) > 0 && fixedLayout[len(fixedLayout)-1] == -1 {
			hasVarTail = true
			fixedLayout = fixedLayout[:len(fixedLayout)-1]
		}
		fmt.Fprintf(&b, "const %s_FIELD_SIZES = [%s];\n", upperName, joinInts(fixedLayout))
		fmt.Fprintf(&b, "const %s_HAS_VAR_TAIL = %v;\n\n", upperName, hasVarTail)

		// Decode snapshot function.
		fmt.Fprintf(&b, "function decode%sSnapshot(snap: Uint8Array, initial: Uint8Array | null, existing?: %s): %s {\n", name, name, name)
		b.WriteString("  let o = 0;\n")

		// Snapshot fields (non-initial).
		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				if field.Initial {
					continue
				}
				writeFieldDecoder(&b, field)
			}
		}

		// Var-tail parsing.
		if ent.VarTail != nil {
			writeVarTailDecoder(&b, ent, g.tailItemTypeName(ent))
		}

		// Initial fields. Multiple initial fields are packed in declaration
		// order into the entity's InitialData byte slice; we walk through
		// with a running offset variable so each decoder reads from its
		// proper position. Without this all initial fields after the first
		// would read from byte 0 and clobber each other.
		hasInitialFields := false
		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				if field.Initial {
					hasInitialFields = true
					break
				}
			}
			if hasInitialFields {
				break
			}
		}
		if hasInitialFields {
			b.WriteString("  let initialOff = 0;\n")
		}
		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				if !field.Initial {
					continue
				}
				writeInitialFieldDecoder(&b, field, ent.InitialData)
			}
		}
		if hasInitialFields {
			// Silence the unused-variable warning when the last field is a
			// scalar (the final advance line is the only "use" of initialOff
			// and gets stripped by tsc DCE if no later field references it).
			b.WriteString("  void initialOff;\n")
		}

		// Return object. Wire metadata is overwritten by the caller; initializing
		// it keeps the interface satisfied even if a future path forgets to set it.
		fmt.Fprintf(&b, "  return { netID: 0, authorityEpoch: 0, producedAtMs: 0, entityType: %d", ent.Kind)
		for _, binding := range ent.Bindings {
			for _, field := range binding.Fields {
				fmt.Fprintf(&b, ", %s", field.Name)
			}
		}
		if ent.VarTail != nil {
			fmt.Fprintf(&b, ", %s", ent.VarTail.Name)
		}
		b.WriteString(" };\n")
		b.WriteString("}\n\n")
	}

	// Authority epochs are uint32 serials. Comparing them as ordinary numbers
	// fails across wraparound (0 is newer than 0xffffffff), so use RFC 1982-style
	// half-range arithmetic. An exact half-range jump is deliberately not newer.
	b.WriteString("function isNewerAuthorityEpoch(candidate: number, current: number): boolean {\n")
	b.WriteString("  const distance = (candidate - current) >>> 0;\n")
	b.WriteString("  return distance !== 0 && distance < 0x80000000;\n")
	b.WriteString("}\n\n")
	b.WriteString("function isNewerFrameSequence(candidate: number, current: number): boolean {\n")
	b.WriteString("  const distance = (candidate - current) >>> 0;\n")
	b.WriteString("  return distance !== 0 && distance < 0x80000000;\n")
	b.WriteString("}\n\n")

	// Decoder class.
	gameName := titleCase(g.schema.Game)
	fmt.Fprintf(&b, "export class %sDeltaDecoder {\n", gameName)
	// Baseline meta caches the last fully-decoded entity so delta frames can
	// restore initial-only fields (e.g. string names that are only transmitted
	// in the initial data block of a full snapshot). Without this, delta
	// decoding would reset those fields to empty strings every tick.
	b.WriteString("  private baselines = new BaselineStore<{ epoch: number; type: number; lastEntity?: AnyEntity }>();\n\n")
	// FreshSnapshot resets delta baselines, but it does not normally reset the
	// highest authority generation observed for a netID. Frames from the same
	// stream can overlap at handoff; retaining this fence prevents a delayed old
	// fresh frame from resurrecting a superseded lifecycle. A *new enclosing
	// stream generation* is different: it supersedes all history from the old
	// stream (including a destination stream that was later rolled back), so
	// acceptFrame clears this map when it advances the stream generation.
	b.WriteString("  private authorityEpochs = new Map<number, number>();\n\n")
	// The viewer's authority epoch scopes the frame sequence. Gate the entire
	// frame before FreshSnapshot can clear baselines or removals can mutate the
	// visible set: delayed frames from the previous host are otherwise able to
	// roll back a decoder that has already accepted the destination stream.
	b.WriteString("  private streamEpoch: number | null = null;\n")
	b.WriteString("  private lastFrameSequence: number | null = null;\n\n")

	b.WriteString("  clear(): void {\n")
	b.WriteString("    this.baselines.clear();\n")
	b.WriteString("    this.authorityEpochs.clear();\n")
	b.WriteString("    this.streamEpoch = null;\n")
	b.WriteString("    this.lastFrameSequence = null;\n")
	b.WriteString("  }\n\n")

	b.WriteString("  private acceptFrame(streamEpoch: number | undefined, sequence: number): { accepted: boolean; streamChanged: boolean } {\n")
	b.WriteString("    if (streamEpoch === undefined) return { accepted: true, streamChanged: false };\n")
	b.WriteString("    const epoch = streamEpoch >>> 0;\n")
	b.WriteString("    const seq = sequence >>> 0;\n")
	b.WriteString("    if (this.streamEpoch === null) {\n")
	b.WriteString("      this.streamEpoch = epoch;\n")
	b.WriteString("      this.lastFrameSequence = seq;\n")
	b.WriteString("      return { accepted: true, streamChanged: true };\n")
	b.WriteString("    }\n")
	b.WriteString("    if (epoch !== this.streamEpoch) {\n")
	b.WriteString("      if (!isNewerAuthorityEpoch(epoch, this.streamEpoch)) return { accepted: false, streamChanged: false };\n")
	b.WriteString("      this.streamEpoch = epoch;\n")
	b.WriteString("      this.lastFrameSequence = seq;\n")
	b.WriteString("      this.baselines.clear();\n")
	b.WriteString("      this.authorityEpochs.clear();\n")
	b.WriteString("      return { accepted: true, streamChanged: true };\n")
	b.WriteString("    }\n")
	b.WriteString("    if (this.lastFrameSequence !== null && !isNewerFrameSequence(seq, this.lastFrameSequence)) return { accepted: false, streamChanged: false };\n")
	b.WriteString("    this.lastFrameSequence = seq;\n")
	b.WriteString("    return { accepted: true, streamChanged: false };\n")
	b.WriteString("  }\n\n")

	b.WriteString("  decode(data: Uint8Array, streamEpoch?: number): DeltaWorldUpdate | null {\n")
	b.WriteString("    const { header, offset: pos0 } = decodeFrameHeader(data, 0);\n")
	b.WriteString("    const frameOrder = this.acceptFrame(streamEpoch, header.seq);\n")
	b.WriteString("    if (!frameOrder.accepted) return null;\n")
	b.WriteString("    let pos = pos0;\n\n")

	// If the server flagged this frame as fresh (first frame for this
	// conn on the sending ReplicationSystem — login or post-handoff),
	// drop every baseline before applying. This is the only way a
	// handoff-initiated full snapshot can land correctly: the incoming
	// Full entries carry the authoritative per-entity state and must
	// replace, not merge with, whatever baselines the previous cell's
	// decoder had accumulated.
	b.WriteString("    const freshSnapshot = (header.flags & FRAME_FLAG_FRESH_SNAPSHOT) !== 0;\n")
	b.WriteString("    if (freshSnapshot) {\n")
	b.WriteString("      this.baselines.clear();\n")
	b.WriteString("    }\n\n")
	b.WriteString("    const freshAuthorityIDs = freshSnapshot && this.streamEpoch !== null ? new Set<number>() : null;\n\n")

	b.WriteString("    const entered: AnyEntity[] = [];\n")
	b.WriteString("    const updated: AnyEntity[] = [];\n\n")

	// Full entries.
	//
	// Full frames come in two flavors: the first-visibility snapshot (which
	// carries InitialData for one-shot fields like pilot name), and periodic
	// full-state keyframes (which carry no initial data). Both go through this
	// loop. To keep initial-only fields alive across keyframes, look up the
	// previous baseline and pass its cached lastEntity as `existing` — the
	// per-entity decoders fall back to `existing?.field` when the initial
	// blob is missing. First-visibility decodes have no baseline yet and so
	// pass `undefined`, which is fine because initial data IS present.
	b.WriteString("    for (let i = 0; i < header.fullCount; i++) {\n")
	b.WriteString("      const { entry, offset: next } = decodeFullEntry(data, pos);\n")
	b.WriteString("      pos = next;\n")
	b.WriteString("      freshAuthorityIDs?.add(entry.netID);\n")
	b.WriteString("      const highestEpoch = this.authorityEpochs.get(entry.netID);\n")
	b.WriteString("      if (highestEpoch !== undefined && entry.epoch !== highestEpoch && !isNewerAuthorityEpoch(entry.epoch, highestEpoch)) continue;\n")
	b.WriteString("      if (highestEpoch === undefined || isNewerAuthorityEpoch(entry.epoch, highestEpoch)) this.authorityEpochs.set(entry.netID, entry.epoch);\n")
	b.WriteString("      const prevBl = this.baselines.get(entry.netID);\n")
	b.WriteString("      const prevMeta = prevBl?.meta;\n")
	b.WriteString("      const previousEntity = prevMeta?.epoch === entry.epoch && prevMeta.type === entry.entityType ? prevMeta.lastEntity : undefined;\n")
	b.WriteString("      const entity = this.decodeEntity(entry.entityType, entry.snapshot, entry.initialData, entry.netID, entry.epoch, entry.producedAtMs, previousEntity);\n")
	b.WriteString("      this.baselines.set(entry.netID, entry.snapshot, { epoch: entry.epoch, type: entry.entityType, lastEntity: entity ?? undefined });\n")
	b.WriteString("      if (entity) entered.push(entity);\n")
	b.WriteString("    }\n\n")

	// Delta entries.
	b.WriteString("    for (let i = 0; i < header.deltaCount; i++) {\n")
	b.WriteString("      const { entry, offset: next } = decodeDeltaEntry(data, pos);\n")
	b.WriteString("      pos = next;\n")
	b.WriteString("      const bl = this.baselines.get(entry.netID);\n")
	b.WriteString("      if (!bl?.meta || bl.meta.epoch !== entry.epoch || bl.meta.type !== entry.entityType) continue;\n")
	b.WriteString("      const fieldSizes = this.fieldSizesFor(entry.entityType);\n")
	b.WriteString("      const hasVarTail = this.hasVarTailFor(entry.entityType);\n")
	b.WriteString("      const newSnap = applyDelta(fieldSizes, hasVarTail, bl.snapshot, entry.deltaData);\n")
	b.WriteString("      const entity = this.decodeEntity(entry.entityType, newSnap, null, entry.netID, entry.epoch, entry.producedAtMs, bl.meta.lastEntity);\n")
	b.WriteString("      this.baselines.set(entry.netID, newSnap, { epoch: entry.epoch, type: entry.entityType, lastEntity: entity ?? undefined });\n")
	b.WriteString("      if (entity) updated.push(entity);\n")
	b.WriteString("    }\n\n")

	// Removed and exited.
	b.WriteString("    const { ids: removed, offset: pos2 } = decodeRemovedIDs(data, pos, header.removedCount);\n")
	b.WriteString("    const { ids: exited, offset: pos3 } = decodeRemovedIDs(data, pos2, header.exitedCount);\n")
	b.WriteString("    const { sequence: processedInputSeq } = decodeInputAck(data, pos3, header.flags);\n\n")

	// Clean up baselines.
	b.WriteString("    for (const id of removed) this.baselines.delete(id);\n")
	b.WriteString("    for (const id of exited) this.baselines.delete(id);\n\n")
	// Once the enclosing stream generation is known, frame ordering protects
	// against delayed resurrection. Retaining tombstones for entities that are
	// no longer visible would otherwise grow this map for the life of a client.
	b.WriteString("    if (this.streamEpoch !== null) {\n")
	b.WriteString("      for (const id of removed) this.authorityEpochs.delete(id);\n")
	b.WriteString("      for (const id of exited) this.authorityEpochs.delete(id);\n")
	b.WriteString("    }\n\n")
	b.WriteString("    if (freshAuthorityIDs) {\n")
	b.WriteString("      for (const id of this.authorityEpochs.keys()) {\n")
	b.WriteString("        if (!freshAuthorityIDs.has(id)) this.authorityEpochs.delete(id);\n")
	b.WriteString("      }\n")
	b.WriteString("    }\n\n")

	b.WriteString("    return {\n")
	b.WriteString("      tick: header.tick, seq: header.seq, freshSnapshot, streamChanged: frameOrder.streamChanged, processedInputSeq,\n")
	b.WriteString("      entered, updated, removed, exited,\n")
	b.WriteString("    };\n")
	b.WriteString("  }\n\n")

	// decodeEntity dispatcher.
	//
	// `existing` is the previously-decoded entity for this netID (if any),
	// threaded through from baseline meta so per-entity decoders can restore
	// initial-only fields (e.g. strings carried only in full-snapshot initial
	// data). Each case narrows the type before passing it through.
	b.WriteString("  private decodeEntity(type_: number, snap: Uint8Array, initial: Uint8Array | null, netID: number, authorityEpoch: number, producedAtMs: number, existing?: AnyEntity): AnyEntity | null {\n")
	b.WriteString("    switch (type_) {\n")
	for _, ent := range g.schema.Entities {
		name := g.entityName(ent)
		fmt.Fprintf(&b,
			"      case %d: { const prev = existing && existing.entityType === %d ? existing : undefined; const e = decode%sSnapshot(snap, initial, prev); e.netID = netID; e.authorityEpoch = authorityEpoch; e.producedAtMs = producedAtMs; return e; }\n",
			ent.Kind, ent.Kind, name)
	}
	b.WriteString("      default: return null;\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n\n")

	// fieldSizesFor dispatcher.
	b.WriteString("  private fieldSizesFor(type_: number): number[] {\n")
	b.WriteString("    switch (type_) {\n")
	for _, ent := range g.schema.Entities {
		upperName := strings.ToUpper(g.entityName(ent))
		fmt.Fprintf(&b, "      case %d: return %s_FIELD_SIZES;\n", ent.Kind, upperName)
	}
	b.WriteString("      default: return [];\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n\n")

	// hasVarTailFor dispatcher.
	b.WriteString("  private hasVarTailFor(type_: number): boolean {\n")
	b.WriteString("    switch (type_) {\n")
	for _, ent := range g.schema.Entities {
		upperName := strings.ToUpper(g.entityName(ent))
		fmt.Fprintf(&b, "      case %d: return %s_HAS_VAR_TAIL;\n", ent.Kind, upperName)
	}
	b.WriteString("      default: return false;\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n")

	b.WriteString("}\n")

	return b.String()
}

// writeVarTailDecoder emits TypeScript that parses the snapshot's var-tail
// into a typed item array on the decoded entity. Called once per decode
// function after all scalar fields have been consumed.
//
// Panics at codegen time if ItemFields is empty — the generated while loop
// would be an infinite loop because no field decoder would advance `o`.
func writeVarTailDecoder(b *strings.Builder, ent EntitySchema, itemType string) {
	vt := ent.VarTail
	if len(vt.ItemFields) == 0 {
		panic(fmt.Sprintf("sdkgen: entity kind %d var-tail %q has no ItemFields; decoder would be an infinite loop", ent.Kind, vt.Name))
	}
	fmt.Fprintf(b, "  const %sByteLen = readUint16(snap, o); o += 2;\n", vt.Name)
	fmt.Fprintf(b, "  const %sEnd = o + %sByteLen;\n", vt.Name, vt.Name)
	fmt.Fprintf(b, "  const %s: %s[] = [];\n", vt.Name, itemType)
	fmt.Fprintf(b, "  while (o < %sEnd) {\n", vt.Name)
	for _, f := range vt.ItemFields {
		writeFieldDecoderIndented(b, f, "    ")
	}
	fmt.Fprintf(b, "    %s.push({ %s });\n", vt.Name, joinItemFieldNames(vt.ItemFields))
	b.WriteString("  }\n")
}

// writeFieldDecoderIndented is writeFieldDecoder with configurable indent, so
// it can be nested inside the while loop for var-tail items.
//
// Panics on unsupported encodings so a new var-tail field type can't silently
// emit missing decoder lines. String is not supported in var-tail items because
// the client-side while-loop needs a fixed stride per iteration; length-prefixed
// strings belong in the fixed-layout portion of the snapshot.
func writeFieldDecoderIndented(b *strings.Builder, field BindingSchemaField, indent string) {
	switch field.Encoding {
	case "f32":
		fmt.Fprintf(b, "%sconst %s = readFloat32(snap, o); o += 4;\n", indent, field.Name)
	case "qvel":
		fmt.Fprintf(b, "%sconst %s = unVel(readInt16(snap, o), %g); o += 2;\n", indent, field.Name, field.Scale)
	case "qangle":
		fmt.Fprintf(b, "%sconst %s = unAngle(readUint16(snap, o)); o += 2;\n", indent, field.Name)
	case "qnorm":
		fmt.Fprintf(b, "%sconst %s = unNorm(snap[o]); o += 1;\n", indent, field.Name)
	case "u8":
		fmt.Fprintf(b, "%sconst %s = snap[o]; o += 1;\n", indent, field.Name)
	case "u16":
		fmt.Fprintf(b, "%sconst %s = readUint16(snap, o); o += 2;\n", indent, field.Name)
	case "u32":
		fmt.Fprintf(b, "%sconst %s = readUint32(snap, o); o += 4;\n", indent, field.Name)
	case "i16":
		fmt.Fprintf(b, "%sconst %s = readInt16(snap, o); o += 2;\n", indent, field.Name)
	case "bool":
		fmt.Fprintf(b, "%sconst %s = !!snap[o]; o += 1;\n", indent, field.Name)
	default:
		panic(fmt.Sprintf("sdkgen: unsupported var-tail field encoding %q for field %q", field.Encoding, field.Name))
	}
}

func joinItemFieldNames(fields []BindingSchemaField) string {
	names := make([]string, len(fields))
	for i, f := range fields {
		names[i] = f.Name
	}
	return strings.Join(names, ", ")
}

// writeFieldDecoder emits a TypeScript line that consumes one scalar field
// from the fixed-layout portion of an entity snapshot. Strings are handled
// separately by writeInitialFieldDecoder (they live in the initial payload),
// so string encodings must not appear here.
func writeFieldDecoder(b *strings.Builder, field BindingSchemaField) {
	switch field.Encoding {
	case "f32":
		fmt.Fprintf(b, "  const %s = readFloat32(snap, o); o += 4;\n", field.Name)
	case "qvel":
		fmt.Fprintf(b, "  const %s = unVel(readInt16(snap, o), %g); o += 2;\n", field.Name, field.Scale)
	case "qangle":
		fmt.Fprintf(b, "  const %s = unAngle(readUint16(snap, o)); o += 2;\n", field.Name)
	case "qnorm":
		fmt.Fprintf(b, "  const %s = unNorm(snap[o]); o += 1;\n", field.Name)
	case "u8":
		fmt.Fprintf(b, "  const %s = snap[o]; o += 1;\n", field.Name)
	case "u16":
		fmt.Fprintf(b, "  const %s = readUint16(snap, o); o += 2;\n", field.Name)
	case "u32":
		fmt.Fprintf(b, "  const %s = readUint32(snap, o); o += 4;\n", field.Name)
	case "i16":
		fmt.Fprintf(b, "  const %s = readInt16(snap, o); o += 2;\n", field.Name)
	case "bool":
		fmt.Fprintf(b, "  const %s = !!snap[o]; o += 1;\n", field.Name)
	default:
		panic(fmt.Sprintf("sdkgen: unsupported snapshot field encoding %q for field %q", field.Encoding, field.Name))
	}
}

// writeInitialFieldDecoder emits one TS decode statement for an
// initial-only field. It assumes a `let initialOff = 0;` variable was
// emitted earlier in the same function and updates that offset after
// each read so subsequent fields find the right bytes.
//
// Supported encodings:
//
//	string — 1-byte length prefix + UTF-8 bytes
//	u8     — 1 byte
//	i8     — 1 byte signed
//	u16    — 2 bytes big-endian unsigned
//	i16    — 2 bytes big-endian signed
//	u32    — 4 bytes big-endian unsigned
//	f32    — 4 bytes IEEE-754 big-endian
//	bool   — 1 byte (0/1)
//
// Unknown encodings fall back to the previous existing-or-zero default
// so a new wire type doesn't silently corrupt other fields' offsets.
func writeInitialFieldDecoder(b *strings.Builder, field BindingSchemaField, _ string) {
	n := field.Name
	switch field.Encoding {
	case "string":
		fmt.Fprintf(b, "  const %s = initial && initialOff < initial.length ? decodeLengthPrefixedStringU8(initial.subarray(initialOff)) : (existing?.%s ?? \"\");\n", n, n)
		fmt.Fprintf(b, "  if (initial && initialOff < initial.length) initialOff += 1 + initial[initialOff];\n")
	case "u8":
		fmt.Fprintf(b, "  const %s = initial && initialOff < initial.length ? initial[initialOff] : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff < initial.length) initialOff += 1;\n")
	case "i8":
		fmt.Fprintf(b, "  const %s = initial && initialOff < initial.length ? (initial[initialOff] << 24 >> 24) : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff < initial.length) initialOff += 1;\n")
	case "u16":
		fmt.Fprintf(b, "  const %s = initial && initialOff + 2 <= initial.length ? readUint16(initial, initialOff) : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff + 2 <= initial.length) initialOff += 2;\n")
	case "i16":
		fmt.Fprintf(b, "  const %s = initial && initialOff + 2 <= initial.length ? readInt16(initial, initialOff) : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff + 2 <= initial.length) initialOff += 2;\n")
	case "u32":
		fmt.Fprintf(b, "  const %s = initial && initialOff + 4 <= initial.length ? readUint32(initial, initialOff) : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff + 4 <= initial.length) initialOff += 4;\n")
	case "f32":
		fmt.Fprintf(b, "  const %s = initial && initialOff + 4 <= initial.length ? readFloat32(initial, initialOff) : (existing?.%s ?? 0);\n", n, n)
		b.WriteString("  if (initial && initialOff + 4 <= initial.length) initialOff += 4;\n")
	case "bool":
		fmt.Fprintf(b, "  const %s = initial && initialOff < initial.length ? (initial[initialOff] !== 0) : (existing?.%s ?? false);\n", n, n)
		b.WriteString("  if (initial && initialOff < initial.length) initialOff += 1;\n")
	default:
		fmt.Fprintf(b, "  const %s = existing?.%s ?? 0;\n", n, n)
	}
}

func joinInts(ints []int) string {
	parts := make([]string, len(ints))
	for i, v := range ints {
		parts[i] = fmt.Sprintf("%d", v)
	}
	return strings.Join(parts, ", ")
}

