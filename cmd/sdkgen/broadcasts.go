package main

import (
	"fmt"
	"strings"
)

// genBroadcasts emits the TypeScript file containing one class per
// broadcast-eligible Go type, plus a TypedDispatcher that routes incoming
// WorldUpdateMsg.events entries to the matching class's decode method.
//
// The wire layout is the reflect_marshal codec defined in
// pkg/universe/reflect_marshal.go: fields encoded in source declaration
// order, no padding, little-endian. mmokit.Entity encodes as a 4-byte
// NetID via the registered reflect codec.
//
// Output schema (per type):
//
//	export class Damage {
//	  static readonly typeID = 0xa1b2c3d4;
//	  amount: number = 0;
//	  ...
//	  static decode(buf: Uint8Array): Damage { ... }
//	}
//
// Plus:
//
//	export class TypedDispatcher {
//	  on<T>(cls, fn): void;
//	  dispatch(typeID, body): void;
//	}
func (g *Generator) genBroadcasts() string {
	var b strings.Builder
	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")
	b.WriteString("// Typed broadcast events. Wire format mirrors the reflect-codec layout\n")
	b.WriteString("// in pkg/universe/reflect_marshal.go: fields encoded in source order,\n")
	b.WriteString("// little-endian, no padding. mmokit.Entity → 4-byte NetID.\n\n")

	for _, bt := range g.schema.BroadcastTypes {
		writeBroadcastClass(&b, bt)
	}

	// Dispatcher class — registers per-class handlers keyed on typeID,
	// invokes the matching class's decode on dispatch. Stale Map<number,
	// Function> avoids per-event closure allocation: each handler captures
	// cls.decode at registration time.
	b.WriteString("/** Dispatches incoming TypedEvent (typeID + body bytes) to typed handlers. */\n")
	b.WriteString("export class TypedDispatcher {\n")
	b.WriteString("  private handlers = new Map<number, (raw: Uint8Array) => void>();\n\n")
	b.WriteString("  /** Register a handler for broadcasts of class T. The class must expose\n")
	b.WriteString("   *  static readonly typeID and static decode(buf): T. */\n")
	b.WriteString("  on<T>(cls: { typeID: number; decode(buf: Uint8Array): T }, fn: (msg: T) => void): () => void {\n")
	b.WriteString("    const handler = (raw: Uint8Array) => fn(cls.decode(raw));\n")
	b.WriteString("    this.handlers.set(cls.typeID, handler);\n")
	b.WriteString("    return () => { if (this.handlers.get(cls.typeID) === handler) this.handlers.delete(cls.typeID); };\n")
	b.WriteString("  }\n\n")
	b.WriteString("  /** Dispatch one incoming wire event. No-op if no handler is registered for typeID. */\n")
	b.WriteString("  dispatch(typeID: number, body: Uint8Array): void {\n")
	b.WriteString("    const fn = this.handlers.get(typeID);\n")
	b.WriteString("    if (fn) fn(body);\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")

	return b.String()
}

// writeBroadcastClass emits one TS class for a broadcast-eligible Go type.
// The class name is the Go type's bare struct name (e.g. "game.Damage" →
// "Damage"). All fields are public + zero-initialized so callers can
// construct + mutate without ceremony; the static decode allocates a new
// instance and consumes the buffer in declaration order.
func writeBroadcastClass(b *strings.Builder, bt BroadcastTypeSchema) {
	className := broadcastClassName(bt.Name)

	fmt.Fprintf(b, "/** Broadcast-eligible event %s (typeID 0x%08x). */\n", bt.Name, bt.TypeID)
	fmt.Fprintf(b, "export class %s {\n", className)
	fmt.Fprintf(b, "  static readonly typeID = 0x%x;\n", bt.TypeID)
	for _, f := range bt.Fields {
		tsType, init := broadcastFieldTSType(f.Encoding)
		fmt.Fprintf(b, "  %s: %s = %s;\n", f.Name, tsType, init)
	}
	b.WriteString("\n")
	fmt.Fprintf(b, "  static decode(buf: Uint8Array): %s {\n", className)
	b.WriteString("    const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);\n")
	b.WriteString("    let off = 0;\n")
	fmt.Fprintf(b, "    const m = new %s();\n", className)
	for _, f := range bt.Fields {
		writeBroadcastFieldDecode(b, f)
	}
	b.WriteString("    return m;\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
}

// broadcastClassName extracts the bare TS class name from a Go type name.
// "game.Damage" → "Damage"; "package.Subpkg.Foo" → "Foo".
func broadcastClassName(goName string) string {
	if i := strings.LastIndex(goName, "."); i >= 0 {
		return goName[i+1:]
	}
	return goName
}

// broadcastFieldTSType maps an encoding tag to (TS type, zero-init expr).
// Mirrors the encodings emitted by pkg/mmokit.fieldSchemaOf — keep in sync.
func broadcastFieldTSType(enc string) (tsType string, init string) {
	switch enc {
	case "f32", "f64",
		"u8", "u16", "u32", "u64",
		"i8", "i16", "i32", "i64",
		"entity":
		return "number", "0"
	case "bool":
		return "boolean", "false"
	case "string":
		return "string", "\"\""
	default:
		panic(fmt.Sprintf("sdkgen: unsupported broadcast field encoding %q", enc))
	}
}

// writeBroadcastFieldDecode emits one decode line for a broadcast-class field.
// Each line consumes its bytes from the DataView and advances `off`. Format
// matches reflect_marshal.unmarshalValueOnStage exactly.
func writeBroadcastFieldDecode(b *strings.Builder, f BroadcastFieldSchema) {
	switch f.Encoding {
	case "f32":
		fmt.Fprintf(b, "    m.%s = dv.getFloat32(off, true); off += 4;\n", f.Name)
	case "f64":
		fmt.Fprintf(b, "    m.%s = dv.getFloat64(off, true); off += 8;\n", f.Name)
	case "u8":
		fmt.Fprintf(b, "    m.%s = dv.getUint8(off); off += 1;\n", f.Name)
	case "u16":
		fmt.Fprintf(b, "    m.%s = dv.getUint16(off, true); off += 2;\n", f.Name)
	case "u32", "entity":
		fmt.Fprintf(b, "    m.%s = dv.getUint32(off, true); off += 4;\n", f.Name)
	case "u64":
		// JS Number can lose precision past 2^53. NetIDs and small counts
		// stay well under that — we accept the cast for ergonomics.
		fmt.Fprintf(b, "    m.%s = Number(dv.getBigUint64(off, true)); off += 8;\n", f.Name)
	case "i8":
		fmt.Fprintf(b, "    m.%s = dv.getInt8(off); off += 1;\n", f.Name)
	case "i16":
		fmt.Fprintf(b, "    m.%s = dv.getInt16(off, true); off += 2;\n", f.Name)
	case "i32":
		fmt.Fprintf(b, "    m.%s = dv.getInt32(off, true); off += 4;\n", f.Name)
	case "i64":
		fmt.Fprintf(b, "    m.%s = Number(dv.getBigInt64(off, true)); off += 8;\n", f.Name)
	case "bool":
		fmt.Fprintf(b, "    m.%s = dv.getUint8(off) !== 0; off += 1;\n", f.Name)
	case "string":
		// Matches reflect_marshal: 2-byte LE length prefix, then UTF-8 bytes.
		fmt.Fprintf(b, "    {\n")
		fmt.Fprintf(b, "      const sl = dv.getUint16(off, true); off += 2;\n")
		fmt.Fprintf(b, "      m.%s = new TextDecoder().decode(buf.subarray(off, off + sl)); off += sl;\n", f.Name)
		fmt.Fprintf(b, "    }\n")
	default:
		panic(fmt.Sprintf("sdkgen: unsupported broadcast field encoding %q for field %q", f.Encoding, f.Name))
	}
}
