package main

import (
	"fmt"
	"strings"
)

// genInputs emits the TypeScript file containing one class per
// HandleClient-eligible Go type. Each class exposes:
//
//   - static readonly typeID (uint32, matches mmokit.TypeIDOf on the server)
//   - per-field public properties initialized to a zero value
//   - encode(): Uint8Array — produces bytes that the server-side
//     ReflectUnmarshalOnStage call site decodes back into the Go struct
//
// The wire layout mirrors the reflect_marshal codec defined in
// pkg/universe/reflect_marshal.go: fields encoded in source declaration
// order, no padding, little-endian. mmokit.Entity encodes as a 4-byte
// NetID via the registered reflect codec.
//
// The full client→server frame layout is:
//
//	[byte 0x02][u32 typeID][u32 bodyLen][body bytes]
//
// The TS class only encodes the body; SpaceClient.send wraps it with
// the channel byte + header.
//
// Output schema (per type):
//
//	export class SetMoveTarget {
//	  static readonly typeID = 0x12345678;
//	  sequence: number = 0;
//	  active: boolean = false;
//	  ...
//	  encode(): Uint8Array { ... }
//	}
func (g *Generator) genInputs() string {
	var b strings.Builder
	b.WriteString("// GENERATED by sdkgen — do not edit.\n\n")
	b.WriteString("// Typed client-input messages. Wire format mirrors the reflect-codec\n")
	b.WriteString("// layout in pkg/universe/reflect_marshal.go: fields encoded in source\n")
	b.WriteString("// order, little-endian, no padding. mmokit.Entity → 4-byte NetID.\n")
	b.WriteString("//\n")
	b.WriteString("// SpaceClient.send(msg) wraps the encoded body in the [0x02][u32 typeID]\n")
	b.WriteString("// [u32 bodyLen][body] frame consumed by the server's HandleClient dispatch.\n\n")

	for _, ct := range g.schema.ClientInputTypes {
		writeClientInputClass(&b, ct)
	}

	return b.String()
}

// writeClientInputClass emits one TS class for a HandleClient-eligible Go type.
// The class name is the Go type's bare struct name (e.g. "game.SetMoveTarget"
// → "SetMoveTarget"). All fields are public + zero-initialized so callers can
// construct + mutate without ceremony; the encode() instance method allocates
// a fresh buffer sized to fit all fields and serializes them in declaration
// order.
//
// Reuses broadcastClassName + broadcastFieldTSType from broadcasts.go: the
// schema shapes are identical and the per-field TS types match exactly.
func writeClientInputClass(b *strings.Builder, ct ClientInputTypeSchema) {
	className := broadcastClassName(ct.Name)

	fmt.Fprintf(b, "/** Client-input message %s (typeID 0x%08x). */\n", ct.Name, ct.TypeID)
	fmt.Fprintf(b, "export class %s {\n", className)
	fmt.Fprintf(b, "  static readonly typeID = 0x%x;\n", ct.TypeID)
	for _, f := range ct.Fields {
		fmt.Fprintf(b, "  %s: %s = %s;\n", f.Name, broadcastFieldTSType(f), broadcastFieldTSInit(f))
	}
	b.WriteString("\n")

	// Constructor accepts a Partial<T> for ergonomic field-init at the
	// call site: `client.send(new SetMoveTarget({ x: 100, y: 200, active: true }))`.
	fmt.Fprintf(b, "  constructor(init?: Partial<%s>) {\n", className)
	b.WriteString("    if (init) Object.assign(this, init);\n")
	b.WriteString("  }\n\n")

	// encode(): Uint8Array.
	//
	// Pre-allocate the exact buffer size by walking the field list. Variable-
	// size strings have to be UTF-8 encoded first to know their byte length.
	// Other field sizes come straight from the schema's Size column.
	b.WriteString("  encode(): Uint8Array {\n")
	writeEncodeBody(b, ct)
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
}

// writeEncodeBody writes the body of encode() — buffer sizing pass first
// (any string fields are UTF-8 encoded into local consts so their .length
// is known up-front), then the actual write pass into the allocated buffer.
//
// Fixed-size-only types take the simpler fast path (size known at codegen
// time, single allocation, no pre-encode).
func writeEncodeBody(b *strings.Builder, ct ClientInputTypeSchema) {
	hasString := false
	fixedSize := 0
	for _, f := range ct.Fields {
		if f.Encoding == "string" {
			hasString = true
		} else {
			fixedSize += f.Size
		}
	}

	if !hasString {
		// Fast path: every field is fixed-size, total known at codegen time.
		fmt.Fprintf(b, "    const buf = new Uint8Array(%d);\n", fixedSize)
		b.WriteString("    const dv = new DataView(buf.buffer);\n")
		b.WriteString("    let off = 0;\n")
		for _, f := range ct.Fields {
			writeClientInputFieldEncode(b, f)
		}
		b.WriteString("    return buf;\n")
		return
	}

	// Variable-size path: pre-encode each string into a local const, sum
	// total size from fixed-size fields + (2 + bytes.length) per string,
	// then do the actual write pass.
	for _, f := range ct.Fields {
		if f.Encoding == "string" {
			fmt.Fprintf(b, "    const _%s = new TextEncoder().encode(this.%s);\n", f.Name, f.Name)
		}
	}
	// Size expression: fixed bytes + (2 + _<name>.length) per string.
	parts := []string{fmt.Sprintf("%d", fixedSize)}
	for _, f := range ct.Fields {
		if f.Encoding == "string" {
			parts = append(parts, fmt.Sprintf("2 + _%s.length", f.Name))
		}
	}
	fmt.Fprintf(b, "    const buf = new Uint8Array(%s);\n", strings.Join(parts, " + "))
	b.WriteString("    const dv = new DataView(buf.buffer);\n")
	b.WriteString("    let off = 0;\n")
	for _, f := range ct.Fields {
		writeClientInputFieldEncode(b, f)
	}
	b.WriteString("    return buf;\n")
}

// writeClientInputFieldEncode emits one encode line for a client-input field.
// Each line writes the field's bytes via DataView (or buf.set for strings)
// and advances `off`. Format mirrors reflect_marshal.marshalValue exactly.
func writeClientInputFieldEncode(b *strings.Builder, f BroadcastFieldSchema) {
	switch f.Encoding {
	case "f32":
		fmt.Fprintf(b, "    dv.setFloat32(off, this.%s, true); off += 4;\n", f.Name)
	case "f64":
		fmt.Fprintf(b, "    dv.setFloat64(off, this.%s, true); off += 8;\n", f.Name)
	case "u8":
		fmt.Fprintf(b, "    dv.setUint8(off, this.%s); off += 1;\n", f.Name)
	case "u16":
		fmt.Fprintf(b, "    dv.setUint16(off, this.%s, true); off += 2;\n", f.Name)
	case "u32", "entity":
		// `entity` rides on the registered reflect codec for mmokit.Entity,
		// which encodes only the 4-byte NetID. Callers pass the NetID as
		// a number on the TS-class field — same shape as broadcast decode.
		fmt.Fprintf(b, "    dv.setUint32(off, this.%s, true); off += 4;\n", f.Name)
	case "u64":
		// JS `number` only safely covers up to 2^53; for the typical
		// mmokit u64 use cases (request sequences, NetIDs) that's enough.
		// BigInt-typed at the boundary; .setBigUint64 wants a BigInt arg.
		fmt.Fprintf(b, "    dv.setBigUint64(off, BigInt(this.%s), true); off += 8;\n", f.Name)
	case "i8":
		fmt.Fprintf(b, "    dv.setInt8(off, this.%s); off += 1;\n", f.Name)
	case "i16":
		fmt.Fprintf(b, "    dv.setInt16(off, this.%s, true); off += 2;\n", f.Name)
	case "i32":
		fmt.Fprintf(b, "    dv.setInt32(off, this.%s, true); off += 4;\n", f.Name)
	case "i64":
		fmt.Fprintf(b, "    dv.setBigInt64(off, BigInt(this.%s), true); off += 8;\n", f.Name)
	case "bool":
		fmt.Fprintf(b, "    dv.setUint8(off, this.%s ? 1 : 0); off += 1;\n", f.Name)
	case "string":
		// Matches reflect_marshal: 2-byte LE length prefix, then UTF-8 bytes.
		// _<name> was pre-encoded by writeEncodeBody so we know its length
		// before the size pass; here we just write the prefix + body bytes.
		fmt.Fprintf(b, "    dv.setUint16(off, _%s.length, true); off += 2;\n", f.Name)
		fmt.Fprintf(b, "    buf.set(_%s, off); off += _%s.length;\n", f.Name, f.Name)
	default:
		panic(fmt.Sprintf("sdkgen: unsupported client-input field encoding %q for field %q", f.Encoding, f.Name))
	}
}
